// ── Units ────────────────────────────────────────────────────

/** Deterministic JSON: object keys sorted, so a reordered source keeps its hash. */
function stableJson(value) {
  if (Array.isArray(value)) return `[${value.map(stableJson).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.keys(value)
      .sort()
      .map((k) => `${JSON.stringify(k)}:${stableJson(value[k])}`)
      .join(",")}}`;
  }
  return JSON.stringify(value);
}

export const enHash = (text) => createHash("sha256").update(stableJson(text)).digest("hex").slice(0, 12);

const hasText = (value) =>
  typeof value === "string" || (Array.isArray(value) ? value.some(hasText) : Boolean(value) && typeof value === "object" && Object.values(value).some(hasText));

const NO_STRUCTURE = new Set();

const pathIn = (at, key) => (at === "" ? String(key) : `${at}.${key}`);

/**
 * The text fields of a pack entry, nested the way the entry nests them; array
 * positions are kept. `structure` holds entry paths (`content.3.rows`) that are
 * structure though their field is a text field; `at` is `value`'s own path.
 */
export function textOf(app, value, structure = NO_STRUCTURE, at = "") {
  if (Array.isArray(value)) {
    return value.map((item, i) => (item && typeof item === "object" ? textOf(app, item, structure, pathIn(at, i)) : undefined));
  }
  const out = {};
  for (const [key, child] of Object.entries(value)) {
    if (structure.has(pathIn(at, key))) continue;
    if (app.textFields.has(key)) out[key] = child;
    else if (child && typeof child === "object") {
      const text = textOf(app, child, structure, pathIn(at, key));
      if (hasText(text)) out[key] = text;
    }
  }
  return out;
}

/** Paths in an en entry where a text field holds one of the app's shared structure values. */
function structurePaths(app, entry, sharedValues) {
  const found = new Set();
  if (!sharedValues.length) return found;
  const shared = new Set(sharedValues.map(stableJson));
  const walk = (value, at) => {
    for (const [key, child] of Object.entries(value)) {
      const path = pathIn(at, key);
      if (app.textFields.has(key) && shared.has(stableJson(child))) found.add(path);
      else if (child && typeof child === "object") walk(child, path);
    }
  };
  walk(entry, "");
  return found;
}

/**
 * en's structure paths by unit id, found by position in en: a language's
 * entry skips the same paths, so a changed shared value reaches it on apply.
 */
function withStructure(app, { ui, pack, shared }) {
  const values = app.shared && shared ? app.shared.values(shared) : [];
  return { ui, pack, structure: new Map(packEntries(app, pack).map(({ id, entry }) => [id, structurePaths(app, entry, values)])) };
}

const uiSegment = (app, id) => {
  const top = id.slice(3).split(".")[0];
  return app.uiSegments.includes(top) ? `ui-${top}` : "ui-site";
};

/** Every entry of a pack (an imported module or a plain object of lists), with its unit id, in source order. */
function packEntries(app, pack) {
  return app.lists.flatMap((list) => (pack?.[list.name] ?? []).map((entry) => ({ list, entry, id: `${list.kind}:${entry[list.key]}` })));
}

/**
 * Every translation unit of the en sources, in source order:
 * `{ id, kind, segment, en, enHash }`. UI segments split by top-level key
 * (the app's uiSegments each alone); pack segments by the list's rule
 * (DingPOS: FAQ category).
 */
export function enUnits(app, { ui, pack, structure = new Map() }) {
  const units = [];
  for (const [id, en] of uiLeaves(ui)) units.push({ id, kind: "ui", segment: uiSegment(app, id), en });
  for (const { list, entry, id } of packEntries(app, pack)) {
    units.push({ id, kind: list.kind, segment: list.segment(entry), en: textOf(app, entry, structure.get(id)) });
  }
  return units.map((unit) => ({ ...unit, enHash: enHash(unit.en) }));
}

/** The current translation of every unit a language's files hold, by unit id; `structure` is en's. */
export function translatedUnits(app, { ui, pack }, structure = new Map()) {
  const out = new Map();
  if (ui) for (const [id, value] of uiLeaves(ui)) out.set(id, value);
  for (const { entry, id } of packEntries(app, pack)) out.set(id, textOf(app, entry, structure.get(id)));
  return out;
}

// ── Merging a translation onto en ────────────────────────────

/**
 * en's entry with its text fields replaced by `text` (shaped like textOf(en)).
 * Throws a readable message when `text` does not fit en's shape.
 */
export function mergeText(app, en, text, where = "", structure = NO_STRUCTURE, path = "") {
  const fail = (message) => {
    throw new Error(where ? `${where}: ${message}` : message);
  };
  if (!text || typeof text !== "object" || Array.isArray(text)) fail("expected an object of text fields");
  const expected = textOf(app, en, structure, path);
  for (const key of Object.keys(text)) if (!(key in expected)) fail(`"${key}" is not a text field of the en entry`);
  const out = Array.isArray(en) ? [] : {};
  for (const [key, child] of Object.entries(en)) {
    const at = where ? `${where}.${key}` : key;
    const childPath = pathIn(path, key);
    if (app.textFields.has(key) && !structure.has(childPath)) {
      out[key] = checkText(child, text[key], at, app.freeLengthFields.has(key));
    } else if (key in expected) {
      if (!Array.isArray(child)) {
        out[key] = mergeText(app, child, text[key], at, structure, childPath);
        continue;
      }
      if (!Array.isArray(text[key]) || text[key].length !== child.length) {
        fail(`"${key}" must have ${child.length} entries, like en`);
      }
      out[key] = child.map((item, i) =>
        item && typeof item === "object" && hasText(textOf(app, item, structure, pathIn(childPath, i)))
          ? mergeText(app, item, text[key][i], `${at}.${i}`, structure, pathIn(childPath, i))
          : item,
      );
    } else {
      out[key] = child;
    }
  }
  return out;
}

function checkText(en, value, at, freeLength) {
  if (typeof en === "string") {
    if (typeof value !== "string" || !value.trim()) throw new Error(`${at}: empty or not a string`);
    if (placeholders(value) !== placeholders(en)) throw new Error(`${at}: placeholders [${placeholders(value)}] differ from en [${placeholders(en)}]`);
    return value;
  }
  if (en.some(Array.isArray)) {
    if (!Array.isArray(value) || value.length !== en.length) throw new Error(`${at}: must have ${en.length} rows, like en`);
    return en.map((row, i) => checkText(row, value[i], `${at}.${i}`, freeLength));
  }
  if (!Array.isArray(value) || value.some((v) => typeof v !== "string" || !v.trim())) {
    throw new Error(`${at}: must be a list of non-empty strings`);
  }
  if (!value.length) throw new Error(`${at}: empty list`);
  if (!freeLength && value.length !== en.length) throw new Error(`${at}: has ${value.length} entries, en has ${en.length}`);
  value.forEach((item, i) => {
    // A free-length list has no en counterpart per entry: it may only use placeholders en uses somewhere.
    const expected = freeLength ? null : placeholders(en[i]);
    const found = placeholders(item);
    const allowed = new Set(en.flatMap((e) => placeholders(e).split(" ").filter(Boolean)));
    if (expected !== null ? found !== expected : found.split(" ").some((p) => p && !allowed.has(p))) {
      throw new Error(`${at}.${i}: placeholders [${found}] differ from en [${expected ?? [...allowed].join(" ")}]`);
    }
  });
  return value;
}

/** Validate one incoming unit value against its en unit; returns an error message or null. */
export function unitProblem(app, unit, value) {
  if (unit.kind === "ui") {
    if (typeof value !== "string") return "not a string";
    if (!value.trim() && !app.mayBeEmpty(unit.id)) return "empty value";
    if (placeholders(value) !== placeholders(unit.en)) {
      return `placeholders [${placeholders(value)}] differ from en [${placeholders(unit.en)}]`;
    }
    return null;
  }
  try {
    mergeText(app, unit.source, value, "", unit.structure);
  } catch (error) {
    return error.message;
  }
  for (const [field, max] of Object.entries(app.maxLength ?? {})) {
    const length = typeof value[field] === "string" ? [...value[field]].length : 0;
    if (length > max) return `${field} is ${length} characters; the limit is ${max}`;
  }
  return null;
}

// ── Reading sources ──────────────────────────────────────────

let importCounter = 0;

/** Import a pack module, bypassing the module cache (apply rewrites packs in-process). */
async function importFresh(file) {
  importCounter += 1;
  return import(`${pathToFileURL(file).href}?v=${importCounter}`);
}

// Not cache-busted: the same module instance the pack itself imports, so en's values and the structure values agree.
const importShared = (file) => import(pathToFileURL(file).href);

const readJson = (file) => JSON.parse(readFileSync(file, "utf8"));

/** en's UI strings and pack, with the structure paths of every pack entry (`structure`, by unit id). */
export async function readEn(paths) {
  return withStructure(paths.app, {
    ui: readJson(paths.ui("en")),
    pack: paths.pack ? await importFresh(paths.pack("en")) : null,
    shared: paths.shared ? await importShared(paths.shared) : null,
  });
}

async function readLanguage(paths, code) {
  return {
    ui: existsSync(paths.ui(code)) ? readJson(paths.ui(code)) : null,
    pack: paths.pack && existsSync(paths.pack(code)) ? await importFresh(paths.pack(code)) : null,
  };
}

/** en units with each pack unit's full en entry attached as `source`, and its structure paths. */
function unitsWithSource(app, en) {
  const entries = new Map(packEntries(app, en.pack).map(({ id, entry }) => [id, entry]));
  return enUnits(app, en).map((unit) => ({ ...unit, source: entries.get(unit.id), structure: en.structure.get(unit.id) }));
}

export function readManifest(paths, code) {
  return existsSync(paths.manifest(code)) ? (readJson(paths.manifest(code)).units ?? {}) : {};
}

function writeManifest(paths, code, units) {
  const sorted = Object.fromEntries(Object.entries(units).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
  const doc = `Per translation unit, the hash of the en text the ${code} translation was made from. Written by \`${command(paths, "apply", code)}\`; do not edit.`;
  mkdirSync(dirname(paths.manifest(code)), { recursive: true });
  writeFileSync(paths.manifest(code), `${JSON.stringify({ "//": doc, units: sorted }, null, 2)}\n`);
}

// ── git ──────────────────────────────────────────────────────

function git(paths, args) {
  try {
    return execFileSync("git", args, { cwd: paths.root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"], maxBuffer: 64 * 1024 * 1024 });
  } catch {
    return null;
  }
}

const RELATIVE_IMPORT = /\bfrom\s+["'](\.{1,2}\/[^"']+)["']/g;

/** A language's (or en's) sources as committed at `ref`, plus the app's shared module; missing files are null. */
async function sourcesAt(paths, code, ref) {
  const dir = mkdtempSync(join(tmpdir(), "l10n-"));
  writeFileSync(join(dir, "package.json"), `{ "type": "module" }\n`);
  // Packs import sibling modules by relative path (Sotto's ring-sizes.js; guides.en.js before it existed), so each is written out at the same ref.
  const staged = new Set();
  const stage = (file) => {
    const path = rel(paths, file);
    if (staged.has(path)) return true;
    const text = git(paths, ["show", `${ref}:${path}`]);
    if (text === null) return false;
    staged.add(path);
    mkdirSync(dirname(join(dir, path)), { recursive: true });
    writeFileSync(join(dir, path), text);
    for (const [, specifier] of text.matchAll(RELATIVE_IMPORT)) stage(resolve(dirname(file), specifier));
    return true;
  };
  const load = async (file, importer) => {
    if (!stage(file)) return null;
    try {
      return await importer(join(dir, rel(paths, file)));
    } catch (error) {
      throw new Error(`${rel(paths, file)} at ${ref} does not load: ${error.message}`);
    }
  };
  const uiText = git(paths, ["show", `${ref}:${rel(paths, paths.ui(code))}`]);
  const shared = paths.shared ? await load(paths.shared, importShared) : null;
  const pack = paths.pack ? await load(paths.pack(code), importFresh) : null;
  return { ui: uiText === null ? null : JSON.parse(uiText), pack, shared };
}

/** For stale units: the en text whose hash the manifest recorded, found in git history. */
async function previousEnTexts(paths, wanted, limit = 100) {
  const found = new Map();
  if (!wanted.size) return found;
  const files = [paths.ui("en"), ...(paths.pack ? [paths.pack("en")] : [])].map((file) => rel(paths, file));
  const revisions = (git(paths, ["rev-list", `--max-count=${limit}`, "HEAD", "--", ...files]) ?? "").split("\n").filter(Boolean);
  for (const revision of revisions) {
    const at = await sourcesAt(paths, "en", revision);
    if (!at.ui || (paths.pack && !at.pack)) continue;
    for (const unit of enUnits(paths.app, withStructure(paths.app, at))) {
      if (wanted.get(unit.id) === unit.enHash && !found.has(unit.id)) found.set(unit.id, unit.en);
    }
    if (found.size === wanted.size) break;
  }
  return found;
}

// ── App repo ─────────────────────────────────────────────────

const STRINGS_ENTRY = /^\s*"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)"\s*;\s*$/;
const STRINGS_NOTE = /^\/\* @([a-z]+)(?: max:(\d+))?(?: — (.*?))? \*\/$/;
const FORMAT_SPECIFIER = /%(\d+\$)?(\.\d+)?(ll|l)?[@dif]/;

const decodeStrings = (raw) =>
  raw.replace(/\\(U[0-9A-Fa-f]{4}|.)/g, (_, c) => (c.length === 5 ? String.fromCharCode(parseInt(c.slice(1), 16)) : { n: "\n", t: "\t", r: "\r" }[c] ?? c));

/** key → { value, note } of an app `.strings` file, in file order; notes come from the line above. */
export function parseStrings(text) {
  const entries = new Map();
  const lines = text.split("\n");
  lines.forEach((line, i) => {
    const match = line.match(STRINGS_ENTRY);
    if (!match) return;
    const note = (lines[i - 1] ?? "").trim().match(STRINGS_NOTE);
    entries.set(match[1], {
      value: decodeStrings(match[2]),
      note: note ? { role: note[1], max: note[2] ? Number(note[2]) : null, gloss: note[3] ?? "" } : null,
    });
  });
  return entries;
}

/** The app's en strings with this language's translation of each, or null when the app repo lacks it. */
export function readAppStrings(app, appRepo, code) {
  const files = appRepoFiles(app, appRepo);
  if (!existsSync(files.strings("en")) || !existsSync(files.strings(code))) return null;
  const en = parseStrings(readFileSync(files.strings("en"), "utf8"));
  const target = parseStrings(readFileSync(files.strings(code), "utf8"));
  const byEn = new Map();
  for (const [key, { value, note }] of en) {
    const translated = target.get(key)?.value;
    if (translated === undefined) continue;
    if (!byEn.has(value)) byEn.set(value, []);
    byEn.get(value).push({ key, value: translated, note });
  }
  return byEn;
}

/** First app key whose en equals `en`, plus the others when they translate it differently. */
function appMatchFor(appStrings, en) {
  const matches = appStrings?.get(en);
  if (!matches?.length) return null;
  const [first, ...rest] = matches;
  const alternatives = rest.filter((m) => m.value !== first.value);
  return alternatives.length ? { ...first, alternatives } : first;
}

const escapeRegExp = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

function stringsOf(value, out = []) {
  if (typeof value === "string") out.push(value);
  else if (Array.isArray(value)) value.forEach((v) => stringsOf(v, out));
  else if (value && typeof value === "object") Object.values(value).forEach((v) => stringsOf(v, out));
  return out;
}

/** App buttons, titles, tabs, menus and headers whose en value appears verbatim (whole words) in `texts`. */
export function appTermsFor(appStrings, texts) {
  if (!appStrings) return [];
  const haystack = texts.join("\n");
  const terms = [];
  for (const [en, matches] of appStrings) {
    if (en.length < 3 || FORMAT_SPECIFIER.test(en) || en.includes("\n")) continue;
    const named = matches.find((m) => APP_TERM_ROLES.has(m.note?.role));
    if (!named) continue;
    if (!new RegExp(`(?<![\\p{L}\\p{N}])${escapeRegExp(en)}(?![\\p{L}\\p{N}])`, "u").test(haystack)) continue;
    terms.push({ en, value: named.value, role: named.note.role, key: named.key });
  }
  return terms;
}

// ── new ──────────────────────────────────────────────────────

export function newLanguage(paths, code) {
  const entry = translatedLanguage(paths, code);
  const written = [];
  if (!existsSync(paths.manifest(code))) {
    writeManifest(paths, code, {});
    written.push(paths.manifest(code));
  }
  if (!existsSync(paths.siteGlossary(code))) {
    const template = readFileSync(paths.glossaryTemplate, "utf8");
    const text = template
      .replace(/^# Site glossary template/, `# Site glossary — ${entry.label} (${code})`)
      .replace(/^`npm run l10n -- [a-z]+ new <code>` copies this file.*$/m, `Copied from \`_template.md\`. The ${code} translator fills it before translating any packet, and the reviewer holds every ${code} value to it.`)
      .replaceAll("<code>", code);
    mkdirSync(dirname(paths.siteGlossary(code)), { recursive: true });
    writeFileSync(paths.siteGlossary(code), text);
    written.push(paths.siteGlossary(code));
  }
  return written;
}

// ── sync ─────────────────────────────────────────────────────

/**
 * Units a language must translate: never translated, or translated from an
 * en text that has changed since (stale). Review mode: every translated unit.
 * `onlyIds` narrows either set (re-review of what a fix changed).
 */
export function pendingUnits(units, manifest, current, mode = "translate", onlyIds = null) {
  return units.filter((unit) => {
    if (onlyIds && !onlyIds.has(unit.id)) return false;
    const translated = current.has(unit.id) && unit.id in manifest;
    if (mode === "review") return translated;
    return !translated || manifest[unit.id] !== unit.enHash;
  });
}

/** Unit ids whose translation differs from the one committed at `ref` (new ones included). */
export async function changedSince(paths, code, ref, structure) {
  // git() returns null on any failure; a mistyped ref must not read as "nothing was translated then".
  if (git(paths, ["rev-parse", "--verify", "--quiet", `${ref}^{commit}`]) === null) {
    throw new UsageError(`--since ${ref} is not a commit in this checkout`);
  }
  const before = translatedUnits(paths.app, await sourcesAt(paths, code, ref), structure);
  const now = translatedUnits(paths.app, await readLanguage(paths, code), structure);
  return new Set([...now].filter(([id, value]) => stableJson(before.get(id)) !== stableJson(value)).map(([id]) => id));
}

/**
 * `since` narrows the packets to units whose translation changed since that
 * ref; `ids` adds units to that set (a re-review of findings a fix round kept
 * unchanged), or narrows to just those units without `since`.
 */
export async function sync(paths, code, { mode = "translate", since = null, ids = null, appRepo = paths.app.appRepo } = {}) {
  translatedLanguage(paths, code);
  const en = await readEn(paths);
  const units = enUnits(paths.app, en);
  const manifest = readManifest(paths, code);
  const current = translatedUnits(paths.app, await readLanguage(paths, code), en.structure);
  let onlyIds = since ? await changedSince(paths, code, since, en.structure) : null;
  if (ids?.length) onlyIds = new Set([...(onlyIds ?? []), ...ids]);
  const wanted = pendingUnits(units, manifest, current, mode, onlyIds);
  const stale = new Map(wanted.filter((u) => current.has(u.id) && u.id in manifest && manifest[u.id] !== u.enHash).map((u) => [u.id, manifest[u.id]]));
  const previous = await previousEnTexts(paths, stale);

  // The app's wording is part of every packet; a missing app checkout is a setup error, not a lighter packet.
  const files = appRepoFiles(paths.app, appRepo);
  const required = [files.strings("en"), files.strings(code), ...(files.glossary ? [files.glossary(code)] : [])];
  const missing = required.filter((file) => !existsSync(file));
  if (missing.length) throw new UsageError(`the ${paths.app.name} app repo lacks ${missing.join(", ")} — pass --app-repo <path to the app checkout>`);
  const appStrings = readAppStrings(paths.app, appRepo, code);

  const outDir = paths.logs(code, "packets");
  mkdirSync(outDir, { recursive: true });
  for (const file of readdirSync(outDir)) if (file.endsWith(".json")) unlinkSync(join(outDir, file));

  const segments = new Map();
  for (const unit of wanted) {
    if (!segments.has(unit.segment)) segments.set(unit.segment, []);
    segments.get(unit.segment).push(unit);
  }
  const index = [];
  for (const [segment, list] of segments) {
    const packetUnits = list.map((unit) => {
      const out = { id: unit.id, en: unit.en, enHash: unit.enHash };
      if (unit.kind === "ui") {
        const match = appMatchFor(appStrings, unit.en);
        if (match) out.appMatch = match;
      }
      if (current.has(unit.id)) out.current = current.get(unit.id);
      if (stale.has(unit.id)) {
        out.stale = true;
        out.previousEn = previous.get(unit.id) ?? null;
      }
      return out;
    });
    const packet = {
      app: paths.appName,
      contract: paths.app.contract,
      lang: code,
      segment,
      mode,
      output: rel(paths, paths.logs(code, "out", `${segment}.json`)),
      glossary: {
        app: files.glossary ? files.glossary(code) : null,
        site: rel(paths, paths.siteGlossary(code)),
      },
      count: packetUnits.length,
      units: packetUnits,
      ...(segment.startsWith("ui-") ? {} : { appTerms: appTermsFor(appStrings, list.flatMap((u) => stringsOf(u.en))) }),
    };
    const file = join(outDir, `${segment}.json`);
    writeFileSync(file, `${JSON.stringify(packet, null, 2)}\n`);
    index.push({ segment, count: packetUnits.length, appMatch: packetUnits.filter((u) => u.appMatch).length, packet: rel(paths, file) });
  }
  writeFileSync(join(outDir, "index.json"), `${JSON.stringify({ app: paths.appName, lang: code, mode, since, ids, total: wanted.length, segments: index }, null, 2)}\n`);
  return { total: wanted.length, segments: index };
}

// ── apply ────────────────────────────────────────────────────

/**
 * Rebuild `en` (a UI strings object) with the language's values, keeping en's
 * arrays as arrays (pages `.map()` over `items` lists). Keys without a value
 * are left out; a missing array entry becomes null, which the build rejects.
 */
function rebuildUi(en, values, path = []) {
  const valueAt = (key, child) => {
    const at = [...path, key];
    if (child && typeof child === "object") {
      const nested = rebuildUi(child, values, at);
      return Object.keys(nested).length ? nested : undefined;
    }
    return values.get(`ui:${at.join(".")}`);
  };
  if (Array.isArray(en)) {
    const items = en.map((child, i) => valueAt(i, child));
    return items.every((item) => item === undefined) ? [] : items.map((item) => item ?? null);
  }
  const out = {};
  for (const [key, child] of Object.entries(en)) {
    if (key === "//") continue;
    const value = valueAt(key, child);
    if (value !== undefined) out[key] = value;
  }
  return out;
}

/**
 * The language's pack rebuilt on en: every structure field from en, text from
 * the language. A unit whose translation no longer fits en's shape (en added a
 * step) is stale anyway; its old entry is kept as is until it is re-translated.
 */
function rebuildPack(app, en, values, oldPack) {
  const pack = {};
  for (const list of app.lists) {
    const old = new Map((oldPack?.[list.name] ?? []).map((entry) => [entry[list.key], entry]));
    pack[list.name] = (en.pack[list.name] ?? [])
      .map((entry) => {
        const id = `${list.kind}:${entry[list.key]}`;
        if (!values.has(id)) return null;
        try {
          return mergeText(app, entry, values.get(id), id, en.structure.get(id));
        } catch {
          return old.get(entry[list.key]) ?? null;
        }
      })
      .filter(Boolean);
  }
  return pack;
}

export function renderOutputs(paths, code, en, values, oldPack) {
  const ui = rebuildUi(en.ui, values);
  const pack = rebuildPack(paths.app, en, values, oldPack);
  const note = generatedNote(paths, code);
  const outputs = { [paths.ui(code)]: `${JSON.stringify({ "//": note, ...ui }, null, 2)}\n` };
  if (paths.pack) {
    outputs[paths.pack(code)] = [
      `// ${note}`,
      "",
      ...paths.app.lists.flatMap((list) => [`export const ${list.name} = ${JSON.stringify(pack[list.name], null, 2)};`, ""]),
    ].join("\n");
  }
  return outputs;
}

const outFiles = (paths, code) => {
  const dir = paths.logs(code, "out");
  if (!existsSync(dir)) return [];
  // Oldest first, so a fix round's output overrides the first translation of a unit.
  return readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .map((f) => join(dir, f))
    .sort((a, b) => statSync(a).mtimeMs - statSync(b).mtimeMs || a.localeCompare(b));
};

/**
 * Read translator outputs, validate every unit, then write the language's
 * strings, pack and manifest. Nothing is written on a dry run. A unit
 * translated from an older en is rejected unless a later output covers it.
 */
export async function apply(paths, code, { files = null, dryRun = false } = {}) {
  translatedLanguage(paths, code);
  const en = await readEn(paths);
  const units = new Map(unitsWithSource(paths.app, en).map((u) => [u.id, u]));
  const language = await readLanguage(paths, code);
  const values = translatedUnits(paths.app, language, en.structure);
  const manifest = readManifest(paths, code);
  const rejected = [];
  const outdated = new Set();
  const incoming = new Map();
  const enIssues = [];

  for (const file of files ?? outFiles(paths, code)) {
    const name = relative(paths.root, file);
    let data;
    try {
      data = readJson(file);
    } catch (error) {
      rejected.push(`${name}: not valid JSON (${error.message})`);
      continue;
    }
    if (data.lang && data.lang !== code) {
      rejected.push(`${name}: written for ${data.lang}, not ${code}`);
      continue;
    }
    enIssues.push(...(data.enIssues ?? []).map((issue) => ({ ...issue, file: name })));
    for (const { id, enHash: hash, value } of data.units ?? []) {
      const unit = units.get(id);
      if (!unit) rejected.push(`${id}: not a unit of the en sources`);
      else if (hash !== unit.enHash) outdated.add(id);
      else {
        const problem = unitProblem(paths.app, unit, value);
        if (problem) rejected.push(`${id}: ${problem}`);
        else incoming.set(id, value);
      }
    }
  }
  for (const id of outdated) {
    if (!incoming.has(id)) rejected.push(`${id}: translated from an older en text — sync and translate it again`);
  }

  if (!dryRun && (incoming.size || values.size)) {
    for (const [id, value] of incoming) {
      values.set(id, value);
      manifest[id] = units.get(id).enHash;
    }
    for (const [file, text] of Object.entries(renderOutputs(paths, code, en, values, language.pack))) {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, text);
    }
    const kept = translatedUnits(paths.app, await readLanguage(paths, code), en.structure);
    writeManifest(paths, code, Object.fromEntries(Object.entries(manifest).filter(([id]) => units.has(id) && kept.has(id))));
  }
  return { written: dryRun ? 0 : incoming.size, valid: incoming.size, rejected, enIssues };
}

// ── check ────────────────────────────────────────────────────

/**
 * Problems of every shipped translated language of the app: units missing or
 * extra against en, units translated from an en text that has changed since
 * (stale), and generated files that differ from a fresh rebuild (hand-edited,
 * or an en structure change not yet applied). `npm test` runs this on the repo.
 */
export async function check(paths) {
  const en = await readEn(paths);
  const units = enUnits(paths.app, en);
  const unitIds = new Set(units.map((u) => u.id));
  const problems = [];
  for (const { code } of readRegistry(paths).filter((l) => l.kind === "translated" && l.shipped)) {
    const language = await readLanguage(paths, code);
    const current = translatedUnits(paths.app, language, en.structure);
    const manifest = readManifest(paths, code);
    const list = (label, ids, hint) => {
      if (ids.length) problems.push(`${paths.appName} ${code}: ${ids.length} ${label} — ${ids.join(", ")} — ${hint}`);
    };
    list("missing unit(s)", units.filter((u) => !current.has(u.id) || !(u.id in manifest)).map((u) => u.id), command(paths, "sync", code));
    list("stale unit(s)", units.filter((u) => u.id in manifest && manifest[u.id] !== u.enHash).map((u) => u.id), `en changed since translation; ${command(paths, "sync", code)}`);
    const extra = [...new Set([...Object.keys(manifest), ...current.keys()])].filter((id) => !unitIds.has(id));
    list("extra unit(s)", extra, `not in en; ${command(paths, "apply", code)}`);
    // Without a manifest the language has never been through apply: its files are not generated yet, and every unit is missing.
    if (!existsSync(paths.manifest(code))) continue;
    for (const [file, text] of Object.entries(renderOutputs(paths, code, en, current, language.pack))) {
      if (!existsSync(file) || readFileSync(file, "utf8") !== text) {
        problems.push(`${paths.appName} ${code}: ${rel(paths, file)} is not what apply generates (edited by hand, or en structure changed) — ${command(paths, "apply", code)}`);
      }
    }
  }
  return problems;
}

// ── progress ─────────────────────────────────────────────────

export const stateDir = () => process.env.ALUSTUDIO_SITE_L10N_STATE ?? join(homedir(), ".local/state/alustudio-site-l10n");
const progressFile = (paths) => join(stateDir(), paths.appName, "progress.json");

/** The rollout state of one app: every translated language in registry order; shipped ones start as done. */
export function loadProgress(paths) {
  if (existsSync(progressFile(paths))) return readJson(progressFile(paths));
  const languages = readRegistry(paths).filter((l) => l.kind === "translated");
  return {
    order: languages.map((l) => l.code),
    languages: Object.fromEntries(languages.map((l) => [l.code, { status: l.shipped ? "done" : "pending" }])),
  };
}

function saveProgress(paths, data) {
  mkdirSync(dirname(progressFile(paths)), { recursive: true });
  const tmp = `${progressFile(paths)}.tmp`;
  writeFileSync(tmp, `${JSON.stringify(data, null, 2)}\n`);
  renameSync(tmp, progressFile(paths));
}

const coerce = (value) => (value === "true" || value === "false" ? value === "true" : /^-?\d+$/.test(value) ? Number(value) : value);

export function progress(paths, args) {
  const [verb, code, ...pairs] = args;
  const data = loadProgress(paths);
  switch (verb ?? "show") {
    case "show":
      return JSON.stringify(data, null, 2);
    case "path":
      return progressFile(paths);
    case "next":
      return data.order.find((c) => ["pending", "running"].includes(data.languages[c]?.status)) ?? "";
    case "report": {
      if (!code) break;
      const file = join(stateDir(), paths.appName, "reports", `${code}.md`);
      mkdirSync(dirname(file), { recursive: true });
      return file;
    }
    case "get":
      if (!code) break;
      return JSON.stringify(data.languages[code] ?? {}, null, 2);
    case "set": {
      if (!code || !pairs.length) break;
      translatedLanguage(paths, code);
      const entry = (data.languages[code] ??= { status: "pending" });
      if (!data.order.includes(code)) data.order.push(code);
      for (const pair of pairs) {
        const eq = pair.indexOf("=");
        if (eq < 1) throw new UsageError(`expected key=value, got "${pair}"`);
        const parts = pair.slice(0, eq).split(".");
        let target = entry;
        for (const part of parts.slice(0, -1)) target = target[part] ??= {};
        target[parts.at(-1)] = coerce(pair.slice(eq + 1));
      }
      entry.updatedAt = new Date().toISOString();
      saveProgress(paths, data);
      return JSON.stringify(entry);
    }
  }
  throw new UsageError(`usage: npm run l10n -- ${paths.appName} progress show | path | next | report <code> | get <code> | set <code> key=value [a.b=value …]`);
}

// ── CLI ──────────────────────────────────────────────────────

function flag(args, name) {
  const i = args.indexOf(name);
  if (i === -1) return null;
  const value = args[i + 1];
  args.splice(i, 2);
  return value;
}

async function runCheck(appNames) {
  const problems = [];
  for (const appName of appNames) problems.push(...(await check(sitePaths(appName))));
  for (const problem of problems) console.error(`  ✗ ${problem}`);
  console.log(problems.length ? `l10n check failed: ${problems.length} problem(s)` : `l10n check: every shipped translated language of ${appNames.join(", ")} is current with en`);
  return problems.length ? 1 : 0;
}

async function main(argv) {
  const args = [...argv];
  const appName = args.shift();
  if (appName === "check" && !args.length) return runCheck(Object.keys(APPS));
  if (!appName) throw new UsageError(USAGE);
  const paths = sitePaths(appName);
  const verb = args.shift();
  if (verb === "check" && !args.length) return runCheck([appName]);
  if (verb === "progress") {
    console.log(progress(paths, args));
    return 0;
  }
  if (verb === "new" && args[0]) {
    const written = newLanguage(paths, args[0]);
    for (const file of written) console.log(`wrote ${rel(paths, file)}`);
    if (!written.length) console.log(`${args[0]} is already started`);
    console.log(`next: fill ${rel(paths, paths.siteGlossary(args[0]))}, then \`${command(paths, "sync", args[0])}\``);
    return 0;
  }
  if (verb === "sync" && args[0]) {
    const appRepo = flag(args, "--app-repo") ?? paths.app.appRepo;
    const ids = flag(args, "--ids")?.split(",").filter(Boolean) ?? null;
    const options = { mode: flag(args, "--mode") ?? "translate", since: flag(args, "--since"), ids, appRepo: resolve(appRepo) };
    if (!["translate", "review"].includes(options.mode)) throw new UsageError(`--mode must be translate or review`);
    const { total, segments } = await sync(paths, args[0], options);
    for (const s of segments) console.log(`  ${s.segment}: ${s.count} unit(s)${s.appMatch ? `, ${s.appMatch} appMatch` : ""}`);
    console.log(`${appName} ${args[0]}: ${total} unit(s) to ${options.mode} in ${segments.length} segment(s) → ${rel(paths, paths.logs(args[0], "packets"))}/`);
    return 0;
  }
  if (verb === "apply" && args[0]) {
    const code = args.shift();
    const dryRun = args.includes("--dry-run");
    const files = args.filter((a) => a !== "--dry-run").map((f) => (isAbsolute(f) ? f : resolve(f)));
    const result = await apply(paths, code, { files: files.length ? files : null, dryRun });
    const verbText = dryRun ? `${result.valid} unit(s) valid (dry run, nothing written)` : `wrote ${result.written} unit(s)`;
    console.log(`${appName} ${code}: ${verbText}; rejected ${result.rejected.length}`);
    for (const problem of result.rejected) console.error(`  rejected ${problem}`);
    if (result.enIssues.length) console.log(`  ${result.enIssues.length} en issue(s) reported in the outputs`);
    return result.rejected.length ? 1 : 0;
  }
  throw new UsageError(USAGE);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    process.exitCode = await main(process.argv.slice(2));
  } catch (error) {
    if (!(error instanceof UsageError)) throw error;
    console.error(`error: ${error.message}`);
    process.exitCode = 2;
  }
}
