#!/usr/bin/env bash
#
# Turn the FAQ captures from capture-faq-shots.sh into the web images the FAQ
# shot blocks use, and record their sizes.
#
# Local authoring tool, not part of the CI build — the .webp outputs and
# src/data/faq/shot-sizes.js are committed, so CI never runs this and `magick`
# is not a build dependency.
#
# Usage:
#   ./scripts/build-faq-shots.sh <raw-root> [code ...]
#
# Expects <raw-root>/<code>/<name>.png (a whole upright screen) and <name>.crop
# ("x y w h" in points) for every shot in SHOTS, per code (default: every
# language in l10n/languages.json).
#
# What it does, and why:
#   - Crops each capture to its .crop box. Points become pixels at the
#     capture's own scale (png width ÷ 1210, the iPad Pro 11-inch's landscape
#     width in points).
#   - Writes public/faq/<code>/<name>.webp at min(crop width, 1440). A shot
#     renders at half its file width, its size in points on the iPad, capped
#     at the article column (Figure.jsx), so 1440 is 2x the widest it shows.
#   - When that file is wider than 1080, also writes <name>-1080w.webp at
#     exactly 1080 wide for phones; the build (copy-spa-pages.js) requires the
#     phone file to keep the aspect ratio (height within 1 px).
#   - Rewrites the given languages' entries in src/data/faq/shot-sizes.js,
#     keeping the others. A shot's size differs by language, because a longer
#     language wraps its text and the crop grows with it.
#
set -euo pipefail

SRC="${1:-}"
if [[ -z "$SRC" || ! -d "$SRC" ]]; then
  echo "usage: $0 <raw-root> [code ...]" >&2
  exit 1
fi
shift

command -v magick >/dev/null || { echo "magick not found (brew install imagemagick)" >&2; exit 1; }

APP="$(cd "$(dirname "$0")/.." && pwd)"
REG="$APP/l10n/languages.json"
SIZES="$APP/src/data/faq/shot-sizes.js"

SHOTS="dashboard-tiles report-periods profit-not-tracked tax-report tax-export return-boxes input-tax-toggle input-tax-po profit-loss-month expense-form advanced-reports"
SCREEN_POINTS=1210
MAX_WIDTH=1440
PHONE_WIDTH=1080

CODES=("$@")
(( ${#CODES[@]} )) || CODES=($(jq -r '.languages[].code' "$REG"))

# Check every input first so a missing capture never leaves a half-written set.
for code in "${CODES[@]}"; do
  for name in $SHOTS; do
    for ext in png crop; do
      [[ -f "$SRC/$code/$name.$ext" ]] || { echo "missing: $SRC/$code/$name.$ext" >&2; exit 1; }
    done
  done
done

# Encode to a temp file, then publish. Keep .webp last: magick picks the
# encoder from the extension, and a .tmp suffix silently writes PNG bytes.
encode() { # <in> <width> <out>
  local tmp="$(dirname "$3")/.faq-shot.tmp.webp"
  magick "$1" -resize "${2}x" -quality 82 -define webp:method=6 "webp:$tmp"
  mv "$tmp" "$3"
}

entries=$(mktemp /tmp/faq-sizes-XXXXXX)
trap 'rm -f "$entries" /tmp/faq-crop-*.png' EXIT

for code in "${CODES[@]}"; do
  out="$APP/public/faq/$code"
  mkdir -p "$out"
  for name in $SHOTS; do
    in="$SRC/$code/$name.png"
    read -r x y w h <"$SRC/$code/$name.crop"
    scale=$(( $(magick identify -format "%w" "$in") / SCREEN_POINTS ))
    crop=$(mktemp /tmp/faq-crop-XXXXXX).png
    magick "$in" -crop "$(( w * scale ))x$(( h * scale ))+$(( x * scale ))+$(( y * scale ))" +repage "$crop"
    cw=$(magick identify -format "%w" "$crop")
    width=$(( cw < MAX_WIDTH ? cw : MAX_WIDTH ))
    encode "$crop" "$width" "$out/$name.webp"
    if (( width > PHONE_WIDTH )); then
      encode "$crop" "$PHONE_WIDTH" "$out/$name-${PHONE_WIDTH}w.webp"
    else
      rm -f "$out/$name-${PHONE_WIDTH}w.webp"
    fi
    size=$(magick identify -format "%w %h" "$out/$name.webp")
    printf '%s %s %s\n' "$code" "$name" "$size" >>"$entries"
    printf "  ✓ %s/%s.webp  %s  %sK\n" "$code" "$name" "${size/ /x}" "$(( $(wc -c <"$out/$name.webp") / 1024 ))"
    rm -f "$crop"
  done
done

node --input-type=module - "$SIZES" "$entries" <<'EOF'
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
const [sizesPath, entriesPath] = process.argv.slice(2);
const sizes = existsSync(sizesPath) ? structuredClone((await import(pathToFileURL(sizesPath))).default) : {};
const fresh = {};
for (const line of readFileSync(entriesPath, "utf8").trim().split("\n")) {
  const [code, name, w, h] = line.split(" ");
  (fresh[code] ??= {})[name] = [Number(w), Number(h)];
}
Object.assign(sizes, fresh);
const body = Object.keys(sizes)
  .sort()
  .map((code) => {
    const names = Object.keys(sizes[code]).sort();
    return `  ${JSON.stringify(code)}: {\n${names.map((n) => `    ${JSON.stringify(n)}: [${sizes[code][n].join(", ")}],`).join("\n")}\n  },`;
  })
  .join("\n");
writeFileSync(
  sizesPath,
  `// Generated by scripts/build-faq-shots.sh — do not edit by hand.\n// [width, height] of public/faq/<code>/<name>.webp, per language.\nexport default {\n${body}\n};\n`,
);
EOF
echo "  ✓ src/data/faq/shot-sizes.js"
